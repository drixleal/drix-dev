#PROGRAMA: Simulando uma Lista de Instruções (IL)

# Instrução 1: Pegue um número e guarde na memória (variável 'numero_inicial')
numero_inicial = 100
print(f"Passo 1: Começamos com o número {numero_inicial}")

# Instrução 2: Multiplique o número por 2 e salve o resultado (variável 'passo_dois')
passo_dois = numero_inicial * 2
print(f"Passo 2: Após multiplicar por 2, temos {passo_dois}")

# Instrução 3: Divida o resultado anterior por 4 e salve o resultado (variável 'passo_tres')
passo_tres = passo_dois / 4
print(f"Passo 3: Após dividir por 4, temos {passo_tres}")

# Instrução 4: Exiba o resultado final armazenado na memória
print(f"Resultado Final: A instrução terminou com o valor {passo_tres}")